  final String name;
  final String serving;
  final int cal;
  final int protein;
  final int carbs;
  final int fat;
  final String slots;
  final int level;
  final List<String> allergens;
  final List<String> aliases;

  const Food(
    this.name,
    this.serving,
    this.cal,
    this.protein,
    this.carbs,
    this.fat, {
    this.slots = '',
    this.level = 0,
    this.allergens = const [],
    this.aliases = const [],
  });

  List<String> get keys => [name.toLowerCase(), ...aliases];
}

